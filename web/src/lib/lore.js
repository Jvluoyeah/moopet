/** 每次进页面挑一句。同一个位置连续两次不会重复（见 pickTwo）。 */
function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

/**
 * 给两张卡片各挑一句，且**保证两句不同** ——
 * 不保证的话，偶尔会出现"两张卡写着同一句话"，看着像 bug。
 */
export function pickTwo() {
  const a = pick(SCENE_LINES);
  let b = pick(RECORDER_LINES);
  let guard = 0;
  while (b === a && guard < 20) {
    b = pick(RECORDER_LINES);
    guard += 1;
  }
  return { scene: a, note: b };
}
