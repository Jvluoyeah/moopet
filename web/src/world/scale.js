/* 世界尺度表：全场景唯一的"尺子"
   ------------------------------------------------------------
   为什么单独抽一个文件：第一版每个道具各自拍脑袋定尺寸，
   结果遮阳伞比房子高、树只画了根杆、狗站在长椅边像只蚂蚁。
   现在所有尺寸都以**狗**为基准推导：

     狗站立高 DOG = 100（全世界的尺子）
     一扇门 DOOR = 210  → 狗走过去只占门的一半，看着就是"人的房子"
     一层楼 STOREY = 460 → 一栋两层小楼 1000 上下，狗在楼前正好显小
     长椅坐面 95 → 跟狗的肩差不多高，狗能跳上去
     路灯 700 → 楼高的 0.7 倍，是街景里最"高"的小物件
     树 950 → 比大多数房子高，树冠超出画面才有"外面还有世界"的感觉

   取景口径（和 camera.js 联动，改相机要回来对一遍）：
     斜俯视 pitch≈57°、fov 35、dist≈1400 时，
     可视地面 ≈ 1090（纵深）× 1270~1700（横宽）。
     所以广场一屏只看得到一部分——这是故意的，
     要的是"走在街上"而不是"看一张全景图"。
*/

