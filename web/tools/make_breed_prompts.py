def build(code, spec):
    src = io.open(TEMPLATE, encoding='utf-8').read()
    t = src
    zh = spec['zh']
    body = spec['first_body'] + '\n' + spec['tail']
    head = spec['first_head'] + '\n' + spec['tail']

    # 1) 三种第一行 + 一段共用第二行：字面替换（不用正则，见文件头注释）
    for lit, val in ((SAM_FIRST_HEAD, spec['first_head']),
                     (SAM_FIRST_HEAD2, spec['first_head']),
                     (SAM_FIRST_BODY, spec['first_body']),
                     (SAM_TAIL, spec['tail'])):
        if lit not in t:
            raise SystemExit(f'  ! 模板里找不到品种句片段：{lit[:36]}…（改过模板？同步改本脚本）')
        t = t.replace(lit, val)

    # 1.5) 画风锚点：把萨摩耶那套换成**这只狗自己的**。
    #      之前用一套通用的"头大而圆、腿短而粗、圆滚滚"描述所有狗，
    #      那是萨摩耶的体型，套到哈士奇身上就出成了长腿尖嘴狗。
    anc = ANCHORS[zh]
    # 注意用 sub 而不是 search+切片：锚点在每条提示词里都有一份（22 处），
    # 用 search 只会换掉第一处，其余 21 条还是萨摩耶的体型描述（踩过）。
    pat_anchor = re.compile(r'严格沿用参考图的画风与配色，只改姿势、不改画风。下面这几条逐条照抄.*?没有任何过渡与明暗。', re.S)
    n_anchor = len(pat_anchor.findall(t))
    if n_anchor != 22:
        raise SystemExit(f'  ! 模板里画风锚点有 {n_anchor} 处，应当是 22 处')
    t = pat_anchor.sub(lambda m: anc, t)

    # 1.6) 负面词里的体型那一串必须**按品种取反**：
    #      "长腿、修长身形"对哈士奇/边牧/德牧是反的（它们本来就长腿），
    #      否则一边在锚点里要求细高、一边在负面词里禁止细高。
    OLD_NAG = ('长腿，修长身形，运动犬，写实比例，尖嘴，长脸，成年犬，瘦削')
    if OLD_NAG not in t:
        raise SystemExit('  ! 模板里找不到体型负面词')
    t = t.replace(OLD_NAG, spec['nag'])

    # 2) 专属提醒：整块换掉（从标题那行到最后一条 `>` 行）
    m = re.search(r'> \*\*两个针对萨摩耶的专门提醒\*\*[^\n]*\n(?:>[^\n]*\n)*', t)
    if not m:
        raise SystemExit('  ! 模板里找不到"专门提醒"那一段')
    t = t[:m.start()] + spec['notes'] + '\n' + t[m.end():]

    # 3) 英文附录里的品种句
    if not re.search(r'A samoyed,[^.]*\.', t):
        raise SystemExit('  ! 模板里找不到英文品种句')
    t = re.sub(r'A samoyed,[^.]*\.', spec['en'], t)

    # 4) 剩下的名字与路径
    t = t.replace('public/breeds/samoyed/', f'public/breeds/{code}/')
    t = t.replace('docs/出图提示词_萨摩耶.md', 'docs/出图提示词_哈士奇.md')
    t = t.replace('萨摩耶', zh)
    t = t.replace('从萨摩耶那份生成', '从模板生成')

    # 5) 自检：不能有残留，也不能把别的段落误伤
    for bad in ('萨摩耶', 'A samoyed', 'F7F4EC', 'D8D2C4', 'breeds/samoyed'):
        if bad in t:
            raise SystemExit(f'  ! {zh}: 替换后仍残留「{bad}」')
    if '专门提醒' not in t:
        raise SystemExit(f'  ! {zh}: 专属提醒那段被误删了')
    if t.count('```') != src.count('```'):
        raise SystemExit(f'  ! {zh}: 代码块数量对不上，有段落被吃掉或重复')
    if t.count('负面：') != 22 or t.count('姿态：') != 18:
        raise SystemExit(f'  ! {zh}: 提示词条数不对（负面 {t.count("负面：")}/22，'
                         f'姿态 {t.count("姿态：")}/18）')
    if t.count(spec['tail']) < 23:
        raise SystemExit(f'  ! {zh}: 品种句只换了 {t.count(spec["tail"])} 处，'
                         f'应该有 23 处（22 条提示词 + 通用块那一条）')

    # 6) 最后再改开头那句（它本身含"萨摩耶"，放在自检之后免得误报）
    t = t.replace(
        f'> 本文档取代之前那两份{zh}文档（动作帧 / 全部提示词），以这份为准。',
        '> 本文档由 `tools/make_breed_prompts.py` 从萨摩耶那份模板生成：\n'
        '> 规格句、姿态描述、负面词与它**逐字一致**，只有品种句和专属提醒不同。')

    # 7) 去掉提示词代码块内部的 markdown 星号。
    #    代码块里的内容是原样发给模型的，"**低矮长身、腿很短**" 的星号就成了噪声。
    #    只动代码块内部（奇数段），正文里的加粗保留。
    parts = t.split(FENCE)
    for i in range(1, len(parts), 2):
        parts[i] = parts[i].replace('**', '')
    return FENCE.join(parts)


def main():
    only = sys.argv[1] if len(sys.argv) > 1 else None
    made = []
    for code, spec in BREEDS.items():
        if only and only not in (code, spec['zh']):
            continue
        out = os.path.join(DOCS, '出图提示词_' + spec['zh'] + '.md')
        # ⚠️ 先生成、后写文件。写成 io.open(out,'w').write(build(...)) 的话，
        # 文件会**先被截断**、build 再抛错，结果留下一份空文档（踩过）。
        text = build(code, spec)
        io.open(out, 'w', encoding='utf-8').write(text)
        made.append(spec['zh'])
    print('已生成：' + ('、'.join(made) if made else '（无）'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
